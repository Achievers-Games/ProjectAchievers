#!/usr/bin/env node
/**
 * generate-db-types.js
 *
 * Generates TypeScript types from the SQLite schema defined in
 * src-tauri/migrations/*.sql.
 *
 * Type mapping:
 *   TEXT    -> string
 *   INTEGER -> number
 *   REAL    -> number
 *   BOOLEAN -> boolean
 *
 * Columns are optional (nullable) unless declared NOT NULL without a DEFAULT.
 *
 * Output: src/lib/db-types.ts
 */

const fs = require('fs');
const path = require('path');

const MIGRATIONS_DIR = path.resolve(__dirname, '../src-tauri/migrations');
const OUTPUT_FILE = path.resolve(__dirname, '../src/lib/db-types.ts');

const SQL_TO_TS = {
  TEXT: 'string',
  INTEGER: 'number',
  REAL: 'number',
  BOOLEAN: 'boolean',
};

function parseTables(sql) {
  const tables = [];
  // Match "CREATE TABLE [IF NOT EXISTS] <name> (<body>);" including nested parens.
  const createRe = /CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?["`]?(\w+)["`]?\s*\(/gi;

  let match;
  while ((match = createRe.exec(sql)) !== null) {
    const name = match[1];
    const bodyStart = match.index + match[0].length; // after the opening '('
    const body = extractParensBody(sql, bodyStart);
    tables.push({ name, body });
  }
  return tables;
}

/** Extracts the body between the opening '(' and its matching ')' (nested aware). */
function extractParensBody(sql, start) {
  // Depth starts at 1: the opening paren is already consumed by the caller.
  let depth = 1;
  for (let i = start; i < sql.length; i++) {
    if (sql[i] === '(') depth++;
    else if (sql[i] === ')') {
      depth--;
      if (depth === 0) return sql.slice(start, i);
    }
  }
  return sql.slice(start);
}

/** Parses column definitions from a table body, skipping table constraints. */
function parseColumns(body) {
  // Split on top-level commas (CHECK (...) may contain commas).
  const lines = [];
  let depth = 0;
  let current = '';
  for (const ch of body) {
    if (ch === '(') depth++;
    else if (ch === ')') depth--;
    if (ch === ',' && depth === 0) {
      lines.push(current.trim());
      current = '';
    } else {
      current += ch;
    }
  }
  if (current.trim()) lines.push(current.trim());

  const CONSTRAINT_KEYWORDS = /^(PRIMARY|FOREIGN|UNIQUE|CHECK|CONSTRAINT)\b/i;

  return lines
    .filter((line) => line && !CONSTRAINT_KEYWORDS.test(line))
    .map((line) => {
      // Column name is the first token (possibly quoted).
      const nameMatch = line.match(/^["`]?(\w+)["`]?\s+(\w+)/);
      if (!nameMatch) return null;
      const name = nameMatch[1];
      const sqlType = nameMatch[2].toUpperCase();

      const notNull = /\bNOT\s+NULL\b/i.test(line);
      const hasDefault = /\bDEFAULT\b/i.test(line);
      const references = line.match(/\bREFERENCES\s+(\w+)/i);

      // NOT NULL (with or without DEFAULT) can never be null; a column without
      // NOT NULL can hold explicit NULLs.
      const optional = !notNull;
      return {
        name,
        type: `${SQL_TO_TS[sqlType] ?? 'unknown'}${optional ? ' | null' : ''}`,
        references: references ? references[1] : null,
      };
    })
    .filter(Boolean);
}

function toInterfaceName(tableName) {
  return 'DB' + tableName.charAt(0).toUpperCase() + tableName.slice(1).replace(/s$/, '');
}

function toPropertyName(name) {
  // Keep snake_case as-is: the runtime rows use it.
  return name;
}

function generate(declarations) {
  const header =
    '/**\n' +
    ' * GENERATED FILE — do not edit manually.\n' +
    ' * Generated by `npm run db:generate` from src-tauri/migrations/*.sql.\n' +
    ' */\n\n';

  const body = declarations.join('\n\n');
  return header + body + '\n';
}

function main() {
  const files = fs
    .readdirSync(MIGRATIONS_DIR)
    .filter((f) => f.endsWith('.sql'))
    .sort();
  if (files.length === 0) {
    console.error('No migration files found in', MIGRATIONS_DIR);
    process.exit(1);
  }

  const declarations = [];

  for (const file of files) {
    const sql = fs.readFileSync(path.join(MIGRATIONS_DIR, file), 'utf8');
    const tables = parseTables(sql);

    for (const table of tables) {
      const columns = parseColumns(table.body);
      const interfaceName = toInterfaceName(table.name);

      const fields = columns
        .map((c) => `  ${toPropertyName(c.name)}: ${c.type};`)
        .join('\n');

      declarations.push(`export interface ${interfaceName} {\n${fields}\n}`);
    }

    console.log(`✔ ${file}: ${tables.length} table(s) parsed`);
  }

  const output = generate(declarations);
  fs.writeFileSync(OUTPUT_FILE, output);
  console.log(
    `\n✔ Wrote ${declarations.length} interfaces to ${path.relative(process.cwd(), OUTPUT_FILE)}`
  );
}

main();
